// Run only against a disposable backend database. Creates fictional test records.
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { createApi, ApiError } = require("../_test-build/lib/api.js");
const base = process.argv[2];
if (!base || !["127.0.0.1", "localhost"].includes(new URL(base).hostname)) throw new Error("A disposable loopback backend is required.");
let token = null;
const api = createApi(base, () => token, () => { token = null; });
const credentials = { login_identifier: `fictional-${randomUUID()}`, password: `Fictional temporary passphrase ${randomUUID()}` };
const registered = await api.register(credentials);
const session = await api.login(credentials); token = session.access_token;
assert.equal((await api.me()).farmer_id, registered.farmer_id);
const date = days => new Date(Date.now() + days * 86400000).toISOString().slice(0, 10);
const fields = { district: "Matara", region: "fictional-locality", crop: "Corn", land_size_acres: 2, planting_date: date(30), expected_harvest_date: date(120), farmer_declared_season: "Maha" };
const created = await api.create(fields);
assert.equal(created.plan.farmer_declared_season, "Maha"); assert.ok(created.plan.plan_id);
assert.equal(created.workflow.assessment.risk_level, null);
assert.equal(created.workflow.assessment.disclosure_status, "collective_values_withheld");
const id = created.plan.plan_id;
assert.equal((await api.list(new URLSearchParams({ limit: "10", offset: "0", status: "active" }))).total, 1);
assert.equal((await api.read(id)).plan.plan_id, id);
assert.equal((await api.analyze(id)).analysis_status, "completed");
assert.equal((await api.compare(created.plan)).disclosure_status, "collective_values_withheld");
const planning = { plan_id: id, final_crop: fields.crop, district: fields.district, region: fields.region, land_size_acres: fields.land_size_acres, planting_date: fields.planting_date, expected_harvest_date: fields.expected_harvest_date, season: "Maha", variety: null, planting_method: "direct_sowing", corn_product: "field_grain", nursery_sowing_date: null, emergence_date: null, flowering_date: null };
assert.equal((await api.generate(planning)).status, "partial_plan");
const saved = await api.save(planning); assert.equal(saved.personalized_plan.status, "partial_plan");
assert.equal((await api.saved(id)).stale, false);
await api.update(id, { ...fields, land_size_acres: 3 }); assert.equal((await api.saved(id)).stale, true);
const cors = await fetch(base + "/api/cultivation-plans", { method: "OPTIONS", headers: { Origin: "http://127.0.0.1:3102", "Access-Control-Request-Method": "GET", "Access-Control-Request-Headers": "authorization" } });
assert.equal(cors.status, 200); assert.equal(cors.headers.get("access-control-allow-origin"), "http://127.0.0.1:3102");
await api.cancel(id); assert.equal((await api.read(id)).plan.status, "cancelled");
await api.logout();
await assert.rejects(api.me(), error => error instanceof ApiError && error.status === 401); assert.equal(token, null);
console.log("Live API smoke passed: auth, owned CRUD/listing, analysis, comparison, partial planning, stale revisions, CORS, cancellation and logout; disposable fictional records only.");
